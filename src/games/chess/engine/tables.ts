/**
 * PLACED[piece * 64 + square]: value plus placement of a piece on a square,
 * positive for White and negative for Black. `piece` is the board code,
 * `type | (colour << 3)`. Kings are zero here because their table depends on
 * how much material is left.
 */
export const PLACED = new Int16Array(16 * 64);
for (let type = 1; type <= 5; type++) {
  for (let square = 0; square < 64; square++) {
    PLACED[type * 64 + square] = PIECE_VALUE[type] + TABLES[type][square ^ 56];
    PLACED[(type | 8) * 64 + square] = -(PIECE_VALUE[type] + TABLES[type][square]);
  }
}
